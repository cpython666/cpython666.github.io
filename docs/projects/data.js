export function sortProjects(items = projects) {
  return [...items].sort((a, b) => {
    const od = (b.display_order ?? 0) - (a.display_order ?? 0);
    if (od !== 0) return od;
    return (a.id ?? 0) - (b.id ?? 0);
  });
}
